"""Effect of keeping ITU-R P.835-6 rather than P.835-7 (08/2024), evaluated, not asserted.

P.835-7 keeps Annex 1 Sec. 1.1. It differs in two ways that touch this study:
(a) the mid-latitude summer temperature from 53 to 80 km becomes 275 + 111.57755 [1 - exp(0.0237 (h - 53))];
(b) seasonal atmospheres are anchored at 15, 45 and 60 deg N with linear interpolation, which changes
    only Madrid among the three availability sites (40.43 deg N: 85 percent mid, 15 percent low).
Writes p835v7_macros.tex: the largest change of any loss under (a) and of any entry of the
availability table under (b).
"""
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import analysis as AN  # noqa: E402
import thzatm as A  # noqa: E402

OUT = os.path.join(HERE, "out")
ORIG = A.p835_seasonal


def meso(h, kind):
    T, P, rho = ORIG(h, kind)
    if kind == "mid-summer":
        h = np.asarray(h, float)
        T = np.where((h >= 53) & (h < 80), 275 + 111.57755 * (1 - np.exp(0.0237 * (h - 53))), T)
    return T, P, rho


def interp(h, kind):
    if not kind.startswith("mid"):
        return ORIG(h, kind)
    w = (40.43 - 15.0) / (45.0 - 15.0)
    Tm, Pm, rm = ORIG(h, kind)
    Tl, Pl, rl = ORIG(h, "low")
    return w * Tm + (1 - w) * Tl, w * Pm + (1 - w) * Pl, w * rm + (1 - w) * rl


def main():
    cs = np.array(json.load(open(os.path.join(OUT, "windows.json")))["centers"])
    Z = np.load(os.path.join(OUT, "atm.npz"))
    meta = json.load(open(os.path.join(OUT, "atm_meta.json")))
    A.p835_seasonal = meso
    dm = 0.0
    for key in meta:
        if key.startswith("native|") or key.split("|")[0] != "mid-summer":
            continue
        pr, p, hh = key.split("|")
        if meta[key]["rh_s_sea"] < AN.RH_FLOOR or meta[key]["rh_max"] > 1.0:
            continue
        X, _ = AN.atm_case(pr, float(p), float(hh), cs)
        ok = np.isfinite(X) & np.isfinite(Z[key])
        dm = max(dm, float(np.max(np.abs(X[ok] - Z[key][ok]))))
    A.p835_seasonal = interp
    res = dict(np.load(os.path.join(OUT, "avail.npz")))
    h, d = A.annex1_layers()
    hm = h + 0.5 * d
    eg, pg = res["eg"], res["Madrid_pg"]
    new = dict(res)
    shp = (len(pg), len(eg), len(cs), len(AN.SUB))
    g = {w: np.zeros(shp) for w in ("Aref", "Aa2", "Aa2r12", "Tmr")}
    Ts = []
    for i, p in enumerate(pg):
        T, P, rho, _, _ = AN.site_state(hm, "Madrid", p)
        Ts.append(float(T[0]))
        AN.avail_fill(hm, h, d, eg, cs, T, P, rho, i, g)
    for w, a in g.items():
        new[f"Madrid_{w}"] = a
    new["Madrid_Ts"] = np.array(Ts)
    A.p835_seasonal = ORIG
    pts = []
    for k in range(5):
        for which in ("Aref", "Aa2", "Aa2r12"):
            if not np.isfinite(res[f"Madrid_{which}"][:, :, k, :]).all():
                continue
            r0, w0 = AN.rate_samples(res, "Madrid", which, k, cs[k])
            r1, w1 = AN.rate_samples(new, "Madrid", which, k, cs[k])
            a0 = round(100 * float(w0[r0 >= AN.RATE_TARGET].sum()))
            a1 = round(100 * float(w1[r1 >= AN.RATE_TARGET].sum()))
            pts.append(abs(a1 - a0))
            print(k, which, a0, a1, flush=True)
    m = {"PsevenMadridMaxPts": f"{max(pts):d}", "PsevenMesoMaxDb": AN.texsci(dm)}
    with open(os.path.join(HERE, "..", "p835v7_macros.tex"), "w") as f:
        f.write("% Generated by sim/p835v7_check.py. Do not edit by hand.\n")
        for k_ in sorted(m):
            f.write(f"\\newcommand{{\\{k_}}}{{{m[k_]}}}\n")
    print(m)


if __name__ == "__main__":
    main()
