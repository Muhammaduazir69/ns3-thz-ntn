    for name, lat, lon in SITES:
        pg = np.geomspace(0.3, {"Svalbard": 27.5, "Madrid": 39, "Singapore": 54}[name], 24)
        shp = (len(pg), len(eg), len(cs), len(SUB))
        grids = {"": {w: np.zeros(shp) for w in ("Aref", "Aa2", "Aa2r12", "Tmr")}}
        warm = SITE_PROF[name][1]
        if SITE_PROF[name][0] != warm:  # profile-rule sensitivity (round 2, D4)
            grids["_warm"] = {w: np.zeros(shp) for w in ("Aref", "Aa2", "Aa2r12", "Tmr")}
        rhmax, Ts, Ts_w = [], [], []
