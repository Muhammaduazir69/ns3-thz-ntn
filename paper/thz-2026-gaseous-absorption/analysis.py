def stage_short():
    r = R()
    f, pw, ref, cpp, straight, zen = r["f"], list(r["pwv"]), r["ref"], r["cpp"], r["straight"], r["zen"]
    cs = json.load(open(os.path.join(OUT, "windows.json")))["centers"]
    ic = [int(np.argmin(np.abs(f - c))) for c in cs]
    els = np.array(ELEVS, float)
    csc = zen[:, None, :] / np.sin(np.radians(els))[None, :, None]
    # Annex 2, equivalent heights with surface meteorology, and the zenith
    # water-vapor variant with V_t = column; Annex 2 is zenith/sin(el).
    # a2/a2v: P.676-13 Annex 2, the method in force (undefined above 350 GHz);
    # a2r12/a2vr12: the superseded P.676-12 closed form that ITU-Rpy 0.4.0
    # still implements, kept to show what tools built on it report.
    a2 = np.zeros_like(ref)
    a2v = np.zeros_like(ref)
    a2r12 = np.zeros_like(ref)
    a2vr12 = np.zeros_like(ref)
    fz = f
    for i, p in enumerate(pw):
        Ts, Ps, rs = A.atm_state(np.array([0.0]), str(r["prof"][i]), float(r["scale"][i]))
        rho_s, T_s, P_tot = float(rs[0]), float(Ts[0]), float(Ps[0])
        P_dry = P_tot - rho_s * T_s / 216.7  # the ITU-Rpy rev-12 call takes dry pressure
        z = A.p676_13_annex2(fz, 90.0, rho_s, P_tot, T_s)
        zv = A.p676_13_annex2(fz, 90.0, rho_s, P_tot, T_s, V_t=float(r["col"][i]))
        z12 = A.itur_annex2(fz, 90.0, rho_s, P_dry, T_s)
        zv12 = A.itur_annex2(fz, 90.0, rho_s, P_dry, T_s, V_t=float(r["col"][i]))
        inv = 1.0 / np.sin(np.radians(els))[:, None]
        a2[i], a2v[i], a2r12[i], a2vr12[i] = (z[None, :] * inv, zv[None, :] * inv,
                                              z12[None, :] * inv, zv12[None, :] * inv)
        print("annex2", p, flush=True)
    np.savez_compressed(os.path.join(OUT, "short.npz"), csc=csc, a2=a2, a2v=a2v, a2r12=a2r12, a2vr12=a2vr12)
    summarize_short()


def summarize_short():
    r = R()
    s = np.load(os.path.join(OUT, "short.npz"))
    f, pw, ref = r["f"], list(r["pwv"]), r["ref"]
    cs = json.load(open(os.path.join(OUT, "windows.json")))["centers"]
    ic = [int(np.argmin(np.abs(f - c))) for c in cs]
    variants = {"Straight": r["straight"], "Module": r["cpp"], "Csc": s["csc"],
                "AnnexTwo": s["a2"], "AnnexTwoVt": s["a2v"],
                "AnnexTwoRtw": s["a2r12"], "AnnexTwoVtRtw": s["a2vr12"]}
    table = {}
    for k, v in variants.items():
        d = v - ref
        table[k] = {}
        for (name, lo, hi, *_), i in zip(WINDOWS, ic):
            dd = d[:, :, i]
            D = ref[:, :, i] <= AMAX  # operable domain
            if D.sum() == 0:
                D = ref[:, :, i] <= ref[:, :, i].min() + 1e-9
            if not np.isfinite(dd[D]).any():
                # method undefined at this window (P.676-13 Annex 2 above 350 GHz)
                table[k][name] = None
                for suf in ("MaxDb", "MaxPct", "AllPct"):
                    mac(f"Sc{k}{WN[name]}{suf}", "n/a")
                continue
            j = int(np.argmax(np.where(D, np.abs(dd), -1)))
            table[k][name] = (float(dd.flat[j]), float(np.abs(dd[D]).max()),
                              float(np.abs(dd[D] / ref[:, :, i][D]).max()), int(D.sum()))
            mac(f"Sc{k}{WN[name]}MaxDb", np.abs(dd[D]).max(), "{:.2f}")
            mac(f"Sc{k}{WN[name]}MaxPct", 100 * np.abs(dd[D] / ref[:, :, i][D]).max(), "{:.1f}")
            mac(f"Sc{k}{WN[name]}AllPct", 100 * np.abs(dd / ref[:, :, i]).max(), "{:.1f}")
            mac(f"Dom{WN[name]}", int(D.sum()), "{:d}")
        # 30 deg, 10 mm values
        ip, j = pw.index(10.0), ELEVS.index(30)
        for (name, *_), i in zip(WINDOWS, ic):
            mac(f"Sc{k}{WN[name]}Mid", d[ip, j, i], "{:+.2f}") if np.isfinite(d[ip, j, i]) else \
                mac(f"Sc{k}{WN[name]}Mid", "n/a")
    # usable bandwidth: contiguous band within 3 dB of each method's own
    # center loss; error = shortcut minus reference, over the operable domain
    bw = {}
    for (name, lo, hi, *_), i in zip(WINDOWS, ic):
        for ip, p in enumerate(pw):
            for j, e in enumerate(ELEVS):
                if ref[ip, j, i] > AMAX:
                    continue
                b0 = usable_bw(f, ref[ip, j], i)
                for k, v in variants.items():
                    if np.isfinite(v[ip, j, i]):
                        bw.setdefault((k, name), []).append(usable_bw(f, v[ip, j], i) - b0)
                bw.setdefault(("Ref", name), []).append(b0)
    for (k, name), vals in bw.items():
        vals = np.array(vals) if len(vals) else np.array([0.0])
        mac(f"Bw{k}{WN[name]}Max", np.abs(vals).max(), "{:.1f}")
    for k in variants:
        ws_ = [max(np.abs(bw[(k, w[0])])) for w in WINDOWS if (k, w[0]) in bw]
        mac(f"Bw{k}WorstGhz", max(ws_) if ws_ else float("nan"), "{:.1f}")
    json.dump({f"{k}|{n}": v for (k, n), v in bw.items()}, open(os.path.join(OUT, "bw.json"), "w"))
    # Annex 2 worst case restricted to the Sec. 1.1 atmosphere (<= 15 mm)
    m15 = np.array(pw) <= 15.5
    for key, nm in (("a2", "AnnexTwo"), ("a2r12", "AnnexTwoRtw")):
        for (name, *_), i in zip(WINDOWS, ic):
            dd = (s[key] - ref)[m15][:, :, i]
            D = ref[m15][:, :, i] <= AMAX
            if not np.isfinite(dd[D]).any():
                continue
            mac(f"Sc{nm}{WN[name]}DryMaxDb", np.abs(dd[D]).max(), "{:.1f}")
            mac(f"Sc{nm}{WN[name]}DryMaxPct", 100 * np.abs(dd[D] / ref[m15][:, :, i][D]).max(), "{:.0f}")
            sg = np.sign(dd[D])
            mac(f"Sc{nm}{WN[name]}DrySign", "negative" if (sg < 0).all() else ("positive" if (sg > 0).all() else "mixed"))
            sa = np.sign(((s[key] - ref)[:, :, i])[ref[:, :, i] <= AMAX])
            mac(f"Sc{nm}{WN[name]}AllSign", "negative" if (sa < 0).all() else ("positive" if (sa > 0).all() else "mixed"))
    mac("GridPoints", len(pw) * len(ELEVS), "{:d}")
    for (name, lo, hi, *_), i in zip(WINDOWS, ic):
        for pv, tg in ((2.0, "Two"), (10.0, "Ten")):
            mac(f"Ref{tg}Mm{WN[name]}", ref[pw.index(pv), ELEVS.index(30), i], "{:.1f}")
        mac(f"RefZenOneMm{WN[name]}", ref[pw.index(1.0), ELEVS.index(90), i], "{:.1f}")
        mac(f"BwRef{WN[name]}Two", usable_bw(f, ref[pw.index(2.0), ELEVS.index(30)], i), "{:.1f}")
    # worst-case relative error of each shortcut over all windows (operable)
    for k in variants:
        rows_ = [table[k][w[0]] for w in WINDOWS if table[k][w[0]] is not None]
        mac(f"Sc{k}WorstPct", 100 * max(x[2] for x in rows_), "{:.1f}")
        mac(f"Sc{k}WorstDb", max(x[1] for x in rows_),
            "{:.2f}" if max(x[1] for x in rows_) < 1 else "{:.1f}")
    ip, j = pw.index(10.0), ELEVS.index(30)
    for (name, lo, hi, *_), i in zip(WINDOWS, ic):
        mac(f"BwRef{WN[name]}Mid", usable_bw(f, ref[ip, j], i), "{:.1f}")
    # Extremes for the abstract: Annex 2 at 850 GHz and 670 GHz, csc at 10 deg
    d = s["a2"] - ref
    w = [n for n, *_ in WINDOWS]
    k8, k6 = w.index("W850"), w.index("W670")
    mac("AmaxDb", AMAX, "{:.0f}")
    if "ref_launch" in r.files:
        D = ref <= AMAX
        mac("RefLaunchEffectMaxDb", np.abs(r["ref_launch"] - ref)[D].max(), "{:.2f}")
    json.dump({k: v for k, v in table.items()}, open(os.path.join(OUT, "short_table.json"), "w"), indent=1)
    print(json.dumps(table, indent=1))


