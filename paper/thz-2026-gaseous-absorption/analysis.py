def write_macros():
    """Write macros.tex from scratch with only the keys produced in this run
    (review D9: no merge, so a stale value can never survive). Run every
    stage, or every summary stage, in one invocation (see run_all.sh)."""
    path = os.path.join(HERE, "..", "macros.tex")
    with open(path, "w") as f:
        f.write("% Generated by sim/analysis.py. Do not edit by hand.\n")
        for k in sorted(MACROS):
            f.write("\\newcommand{\\%s}{%s}\n" % (k, A.tex_minus(MACROS[k])))
    print(f"wrote {len(MACROS)} macros")


