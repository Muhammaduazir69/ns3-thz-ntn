# Realizable atmosphere (review D1): no supersaturation below 10 km and a
# surface relative humidity of at least RH_FLOOR. A 300 K tropical column
# scaled to 1 mm (surface RH under 2 percent) does not occur; the floor is
# the one judgment here, so 0, 10 and 30 percent are reported as well.
RH_FLOOR = 0.20
STATION_H = [0.0, 2.5, 5.0, 20.0]  # terminal heights (km): sea level, two elevated sites, HAPS
ATM_SHORT = ["Straight", "Module", "Csc", "AnnexTwo", "AnnexTwoVt", "AnnexTwoRtw", "AnnexTwoVtRtw"]
