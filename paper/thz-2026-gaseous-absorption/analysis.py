def stage_sonde():
    """Annex 2 against the Annex 1 reference on measured Ny-Alesund soundings
    (round 2, D2): tests whether the column-to-surface-density ratio
    h_eff = V / rho_s drives the error of the equivalent-height method."""
    S = np.load(os.path.join(HERE, "data", "sondes_nyalesund_year.npz"))
    cs = np.array(json.load(open(os.path.join(OUT, "windows.json")))["centers"])
    els = ELEVS  # the seven elevations of Table III
    rows = []
    for i, date in enumerate(S["date"]):
        z0 = float(S["z0"][i])
        h, d = A.annex1_layers_from(max(z0, 1e-3))
        hm = h + 0.5 * d
        zz = z0 + S["zg"]
        ok = np.isfinite(S["T"][i])
        top = zz[ok][-1]
        # splice above the burst: winter profile October to March, summer otherwise
        season = "high-winter" if date[5:7] in ("10", "11", "12", "01", "02", "03") else "high-summer"
        group = {"12": "win", "01": "win", "02": "win", "06": "sum", "07": "sum", "08": "sum"}.get(date[5:7], "mid")
        Tp, Pp, rp = A.p835_seasonal(hm, season)
        Ttop, Ptop, rtop = A.p835_seasonal(np.array([top]), season)
        below = hm <= top
        T = np.where(below, np.interp(hm, zz[ok], S["T"][i][ok]), Tp)
        lnP = np.interp(hm, zz[ok], np.log(S["P"][i][ok]))
        P = np.where(below, np.exp(lnP), Pp * S["P"][i][ok][-1] / float(Ptop[0]))
        rho = np.where(below, np.interp(hm, zz[ok], S["rho"][i][ok]),
                       np.maximum(rp, 2e-6 * P * 216.7 / T))
        G = A.gamma_grid(cs, hm, T, P, rho)
        n = A.refractive_index(T, P, rho)
        ref = np.array([A.annex1_paths_geo(e, h, d, n) @ G for e in els])
        V = A.column_mm(h, d, rho)
        Ts, Ps, rs = float(S["T"][i][0]), float(S["P"][i][0]), float(S["rho"][i][0])
        inv = 1 / np.sin(np.radians(els))[:, None]
        a2 = A.p676_13_annex2(cs, 90.0, rs, Ps, Ts)[None, :] * inv
        a2v = A.p676_13_annex2(cs, 90.0, rs, Ps, Ts, V_t=V)[None, :] * inv
        Pd = Ps - rs * Ts / 216.7
        a2r = A.itur_annex2(cs, 90.0, rs, Pd, Ts)[None, :] * inv
        rows.append(dict(date=str(date), season=season, group=group, V=V, rho_s=rs, Ts=Ts, heff=V / rs,
                         ref=ref.tolist(), a2=a2.tolist(), a2v=a2v.tolist(), a2r=a2r.tolist()))
        print("sonde", date, round(V, 2), round(V / rs, 2), flush=True)
    json.dump(rows, open(os.path.join(OUT, "sonde.json"), "w"))
    summarize_sonde()


