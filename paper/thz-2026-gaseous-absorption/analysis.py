def rate_samples(res, name, which, k, fc, rule="column", sky="rt"):
    """Rate (Gbit/s) per (column quantile, elevation bin) and its probability.
    The rate integrates log2(1 + SNR(f)) over the 10 GHz channel, so the
    shape of the window inside the channel is counted. The noise is the
    receiver noise plus the sky noise of the model's own gaseous loss,
    T_sky = T_mr (1 - t) + J(2.7 K) t with t = 10^(-A/10). sky='rt' takes
    T_mr from radiative transfer through the site atmosphere along the
    refracted ray (Planck emission, round 3, D25); sky='p618' uses the
    surface approximation T_mr = 37.34 + 0.81 T_s of ITU-R P.618-14 Sec. 3;
    sky=False uses the 290 K antenna of the noise-figure definition;
    sky='none' drops the atmospheric emission (T_mr = 0, background only). rule: 'column' (the cold-season
    profile wherever it stays unsaturated), 'warm' (warm-season profile at
    every column) or 'mix' (half of the year each)."""
    if rule == "mix":
        r1, w1 = rate_samples(res, name, which, k, fc, "column", sky)
        r2, w2 = rate_samples(res, name, which, k, fc, "warm", sky)
        return np.concatenate([r1, r2]), np.concatenate([0.5 * w1, 0.5 * w2])
    sfx = "_warm" if rule == "warm" else ""
    pg, eg = res[f"{name}_pg"], res["eg"]
    Atab = res[f"{name}_{which}{sfx}"][:, :, k, :]
    Tmr_tab = res[f"{name}_Tmr{sfx}"][:, :, k, :]
    Ts_col = res[f"{name}_Ts{sfx}"]
    el = res[f"{name}_el"]
    V = np.minimum(res[f"{name}_V"], pg[-1])
    probs = res[f"{name}_p"]
    pe = np.concatenate([[0.0], 0.5 * (probs[1:] + probs[:-1]), [100.0]])
    w = np.diff(pe) / 100.0
    from scipy.interpolate import RegularGridInterpolator
    eh = np.histogram(el, bins=np.arange(10, 91, 1.0))
    ec = 0.5 * (eh[1][1:] + eh[1][:-1])
    ew = eh[0] / eh[0].sum()
    LV, LE = np.meshgrid(np.log(np.maximum(V, pg[0])), ec, indexing="ij")
    Tsurf = np.interp(LV, np.log(pg), Ts_col)
    re_, hs = 6371.0, TERM["h_sat"]
    dkm = np.sqrt((re_ + hs) ** 2 - (re_ * np.cos(np.radians(ec))) ** 2) - re_ * np.sin(np.radians(ec))
    df = (SUB[1] - SUB[0]) * 1e9
    T_rx = 290.0 * (10 ** (TERM["nf_db"] / 10) - 1)
    rate = np.zeros(LV.shape)
    for q, off in enumerate(SUB):
        it = RegularGridInterpolator((np.log(pg), eg), Atab[:, :, q], bounds_error=False, fill_value=None)
        att = it(np.stack([LV.ravel(), LE.ravel()], 1)).reshape(LV.shape)
        if sky == "rt":
            itm = RegularGridInterpolator((np.log(pg), eg), Tmr_tab[:, :, q], bounds_error=False, fill_value=None)
            Tmr = itm(np.stack([LV.ravel(), LE.ravel()], 1)).reshape(LV.shape)
            t = 10 ** (-att / 10)
            T_sky = Tmr * (1 - t) + A.planck_temperature(2.725, fc + off) * t
        elif sky == "none":
            T_sky = A.planck_temperature(2.725, fc + off) * 10 ** (-att / 10)  # T_mr = 0
        elif sky == "p618":
            T_sky = A.sky_temperature(att, Tsurf)
        else:
            T_sky = 290.0
        T_sys = T_rx + T_sky
        noise = 10 * np.log10(1.380649e-23 * T_sys * df) + 30.0  # dBm
        f = fc + off
        lam = 0.299792458e-3 / f
        fspl = 20 * np.log10(4 * np.pi * dkm / lam)
        snr = (TERM["pt_dbm"] - 10 * np.log10(len(SUB)) + gain_db(TERM["d_sat"], f)
               + gain_db(TERM["d_gnd"], f) - fspl[None, :] - att - noise)
        rate += df * np.log2(1 + 10 ** (snr / 10)) / 1e9
    W = w[:, None] * ew[None, :]
    return rate.ravel(), W.ravel()


def quantile_rate(rate, W, avail):
    o = np.argsort(rate)
    cw = np.cumsum(W[o])
    return float(rate[o][np.searchsorted(cw, 1 - avail)])


