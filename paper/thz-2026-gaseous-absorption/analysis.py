def minimax_set(C, tol, lookahead=False, exclude=()):
    """Smallest greedy line set (continuum always kept) whose worst residual
    over all conditions C[:, lines+1] is at most tol. Returns (order, curve).
    With lookahead, a unit is chosen by the best residual reachable after it
    and one more unit (round 2, D14), unless a single unit already meets tol."""
    nl = C.shape[1] - 1
    tot = C.sum(1)
    acc = C[:, -1].copy()
    chosen, curve = [], [np.abs(tot - acc).max()]
    left = [k for k in range(nl) if k not in exclude]
    res = lambda a: np.abs(tot - a).max()
    while left and curve[-1] > tol:
        one = {k: res(acc + C[:, k]) for k in left}
        best = min(one, key=one.get)
        if lookahead and one[best] > tol and len(left) > 1:
            two = {k: min(res(acc + C[:, k] + C[:, j]) for j in left if j != k) for k in left}
            best = min(left, key=lambda k: (two[k], one[k]))
        acc += C[:, best]
        chosen.append(best)
        left.remove(best)
        curve.append(res(acc))
    return chosen, curve


