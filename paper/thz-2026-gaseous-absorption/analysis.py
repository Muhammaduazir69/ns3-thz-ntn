def mac(name, value, fmt="{:.1f}"):
    assert name.isalpha(), name
    s = fmt.format(value) if not isinstance(value, str) else value
    MACROS[name] = s
    return s


def texsci(x):
    m, e = f"{x:.1e}".split("e")
    return "$%s\\times 10^{%d}$" % (m, int(e))


