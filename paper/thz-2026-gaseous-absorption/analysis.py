# profile is used for columns it can hold below saturation, the warm-season
# profile above (scaled in both cases).
SITE_PROF = {"Svalbard": ("high-winter", "high-summer"), "Madrid": ("mid-winter", "mid-summer"),
             "Singapore": ("low", "low")}
SUB = np.arange(-4.75, 4.76, 0.5)  # 20 sub-band centers spanning exactly the 10 GHz channel


def site_state(hm, name, V):
    """(T, P, rho, profile, scale) for a site and column V, RH <= 1 below 10 km
    whenever the warm profile allows it; columns beyond that are capped."""
    h, d = A.annex1_layers()
    hc = h + 0.5 * d
    cold, warm = SITE_PROF[name]
    for prof in (cold, warm):
        _, _, r0 = A.p835_seasonal(hc, prof)
        sc = V / A.column_mm(h, d, r0)
        T, P, rho = A.p835_seasonal(hm, prof)
        if A.max_rh(hm, T, rho * sc) <= 1.0 or prof == warm:
            return T, P, rho * sc, prof, sc
    raise RuntimeError


def site_state_fixed(hm, prof, V):
    """(T, P, rho) of one seasonal profile scaled to column V."""
    h, d = A.annex1_layers()
    _, _, r0 = A.p835_seasonal(h + 0.5 * d, prof)
    T, P, rho = A.p835_seasonal(hm, prof)
    return T, P, rho * V / A.column_mm(h, d, r0)


def avail_fill(hm, h, d, eg, cs, T, P, rho, i, out):
    n = A.refractive_index(T, P, rho)
    paths = np.array([A.annex1_paths_geo(e, h, d, n) for e in eg])
    inv = 1.0 / np.sin(np.radians(eg))[:, None]
    for k, c in enumerate(cs):
        G = A.gamma_grid(c + SUB, hm, T, P, rho)
        out["Aref"][i, :, k, :] = paths @ G
        # mean radiating temperature of this atmosphere by radiative transfer
        # along the same refracted rays (round 3, D25)
        out["Tmr"][i, :, k, :] = A.sky_temperature_rt(paths, G, T, c + SUB)[1]
        z2 = A.p676_13_annex2(c + SUB, 90.0, float(rho[0]), float(P[0]), float(T[0]))
        out["Aa2"][i, :, k, :] = z2[None, :] * inv
        z12 = A.itur_annex2(c + SUB, 90.0, float(rho[0]),
                            float(P[0]) - float(rho[0]) * float(T[0]) / 216.7, float(T[0]))
        out["Aa2r12"][i, :, k, :] = z12[None, :] * inv


