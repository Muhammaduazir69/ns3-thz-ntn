def stage_prof():
    """Seasonal P.835-6 profiles against the Sec. 1.1 profile at equal column.
    The seasonal atmosphere (the truth) must be realizable (no supersaturation
    below 10 km, surface RH at least RH_FLOOR); the Sec. 1.1 profile scaled to
    the column is the shortcut. Single-factor hybrids are kept only where they
    stay unsaturated (round 2, D5)."""
    cs = json.load(open(os.path.join(OUT, "windows.json")))["centers"]
    h, d = A.annex1_layers()
    hm = h + 0.5 * d
    profs = ["low", "mid-summer", "mid-winter", "high-summer", "high-winter"]
    res = {}
    kept, tkept, skept, rkept = [], [], [], []

    def slant(T_, P_, r_):
        G_ = A.gamma_grid(np.array(cs), hm, T_, P_, r_)
        n_ = A.refractive_index(T_, P_, r_)
        return np.array([A.annex1_paths_geo(e, h, d, n_) @ G_ for e in ELEVS])

    def rh_s(T_, r_):
        return float(r_[0] * T_[0] / 216.7 / A.sat_vapor_pressure(T_[0]))

    for p in PROF_PWV:
        T, P, rho = A.state(hm, pwv_mm=p)
        assert A.max_rh(hm, T, rho) <= 1.0
        res[f"base_{p}"] = slant(T, P, rho)
        for pr in profs:
            T2, P2, r2 = A.state(hm, pwv_mm=p, profile=pr)
            if A.max_rh(hm, T2, r2) > 1.0 or rh_s(T2, r2) < RH_FLOOR:
                continue
            res[f"{pr}_{p}"] = slant(T2, P2, r2)
            kept.append((pr, p))
            # temperature and pressure only: seasonal T and P, Sec. 1.1 humidity shape
            if A.max_rh(hm, T2, rho) <= 1.0:
                res[f"tonly_{pr}_{p}"] = slant(T2, P2, rho)
                tkept.append((pr, p))
            # humidity shape only: Sec. 1.1 T and P, seasonal humidity shape
            if A.max_rh(hm, T, r2) <= 1.0:
                res[f"sonly_{pr}_{p}"] = slant(T, P, r2)
                skept.append((pr, p))
        # humidity scale height 1 to 3 km on the Sec. 1.1 temperature and pressure
        for sk in (1.0, 1.5, 2.5, 3.0):
            T4, P4, r4 = A.state(hm, pwv_mm=p, scale_km=sk)
            if A.max_rh(hm, T4, r4) > 1.0:
                continue
            res[f"rho_{sk}_{p}"] = slant(T4, P4, r4)
            rkept.append((sk, p))
        print("prof", p, flush=True)
    np.savez_compressed(os.path.join(OUT, "prof.npz"), **res)
    json.dump({"kept": kept, "tonly": tkept, "sonly": skept, "rho": rkept},
              open(os.path.join(OUT, "prof_kept.json"), "w"))
    summarize_prof()


