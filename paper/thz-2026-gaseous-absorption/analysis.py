def cpp_grid():
    """C++ sweep cube [pwv, elev, f]; P.835-6 Sec. 1.1 up to 20 mm, the Sec. 2
    low-latitude profile at 30 to 60 mm (see thzatm.profile_for_pwv)."""
    rows = [r for r in load_cpp("cpp_inproc.csv") if float(r["pwv_mm"]) <= 15.5]
    rows += load_cpp("cpp_inproc_lowlat.csv")
    f = np.array(sorted({float(r["freq_ghz"]) for r in rows}))
    scales, cols, profs, data = {}, {}, {}, {}
    for r in rows:
        p = round(float(r["pwv_mm"]), 1)
        scales[p] = float(r["wv_scale"])
        cols[p] = float(r["pwv_mm"])
        profs[p] = "p835-std" if r["profile"] == "global-annual" else "low"
        data[(p, float(r["elev_deg"]), float(r["freq_ghz"]))] = float(r["atten_db"])
    pw = sorted(scales)
    cube = np.array([[[data[(p, e, fi)] for fi in f] for e in ELEVS] for p in pw])
    return f, pw, scales, cols, profs, cube


def stage_ref():
    f, pw, scales, cols, profs, cpp = cpp_grid()
    h, d = A.annex1_layers()
    hm = h + 0.5 * d
    ref = np.zeros_like(cpp)
    ref_launch = np.zeros_like(cpp)  # old convention: elevation used as the launch angle
    straight = np.zeros_like(cpp)
    mirror = np.zeros_like(cpp)
    zen = np.zeros((len(pw), len(f)))
    for i, p in enumerate(pw):
        T, P, rho = A.atm_state(hm, profs[p], scales[p])
        G = A.gamma_grid(f, hm, T, P, rho)
        n = A.refractive_index(T, P, rho)
        for j, e in enumerate(ELEVS):
            # theta is the geometric elevation of the satellite (review M5); the
            # refracted reference launches at the apparent elevation that reaches it
            ref[i, j] = A.annex1_paths_geo(e, h, d, n) @ G
            ref_launch[i, j] = A.annex1_path_lengths(e, h, d, n) @ G
            straight[i, j] = A.annex1_path_lengths(e, h, d, None) @ G
            hmm, ds = A.module_slab_weights(e)
            Tm, Pm, rm = A.atm_state(hmm, profs[p], scales[p])
            mirror[i, j] = ds @ A.gamma_grid(f, hmm, Tm, Pm, rm)
        zen[i] = A.annex1_path_lengths(90.0, h, d, n) @ G
        print("ref pwv", p, flush=True)
    np.savez_compressed(os.path.join(OUT, "ref.npz"), f=f, pwv=np.array(pw),
                        col=np.array([cols[p] for p in pw]), scale=np.array([scales[p] for p in pw]),
                        prof=np.array([profs[p] for p in pw]),
                        cpp=cpp, ref=ref, ref_launch=ref_launch, straight=straight, mirror=mirror, zen=zen)


def R():
    return np.load(os.path.join(OUT, "ref.npz"))


def centers(r):
    """Window centers: reference minimum at 30 deg, PWV 10 mm."""
    f = r["f"]
    ip = list(r["pwv"]).index(10.0)
    j = ELEVS.index(30)
    out = []
    for name, lo, hi, slo, shi in WINDOWS:
        m = (f >= slo) & (f <= shi)
        out.append(float(f[m][np.argmin(r["ref"][ip, j][m])]))
    return out


def usable_bw(f, a, ic, rel=3.0):
    """Contiguous bandwidth around the window center index ic over which the
    loss stays within rel dB of its own value at the center (eq. bw)."""
    thr = a[ic] + rel
    lo = ic
    while lo > 0 and a[lo - 1] <= thr:
        lo -= 1
    hi = ic
    while hi < len(a) - 1 and a[hi + 1] <= thr:
        hi += 1
    return (hi - lo) * (f[1] - f[0])


