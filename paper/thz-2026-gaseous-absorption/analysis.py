def elevation_samples(lat, lon, days=10, dt=5.0, emin=10.0):
    """Elevation samples (deg) of one circular LEO over a site (Keplerian, no J2)."""
    mu = 398600.4418
    re = 6371.0
    a = re + TERM["h_sat"]
    n = math.sqrt(mu / a ** 3)
    we = 7.2921159e-5
    inc = math.radians(TERM["inc_deg"])
    t = np.arange(0, days * 86400.0, dt)
    out = []
    lat_r, lon_r = math.radians(lat), math.radians(lon)
    g = re * np.array([math.cos(lat_r) * math.cos(lon_r), math.cos(lat_r) * math.sin(lon_r), math.sin(lat_r)])
    up = g / np.linalg.norm(g)
    for raan in np.radians(np.arange(0, 360, 30)):
        u = n * t
        x = a * (np.cos(raan) * np.cos(u) - np.sin(raan) * np.sin(u) * math.cos(inc))
        y = a * (np.sin(raan) * np.cos(u) + np.cos(raan) * np.sin(u) * math.cos(inc))
        z = a * np.sin(u) * math.sin(inc)
        th = we * t
        xe = np.cos(th) * x + np.sin(th) * y
        ye = -np.sin(th) * x + np.cos(th) * y
        v = np.stack([xe, ye, z], 1) - g
        el = np.degrees(np.arcsin((v @ up) / np.linalg.norm(v, axis=1)))
        out.append(el[el >= emin])
    return np.concatenate(out)


def gain_db(D, f_ghz):
    lam = 0.299792458 / f_ghz
    return 10 * math.log10(TERM["eta"] * (math.pi * D / lam) ** 2)


