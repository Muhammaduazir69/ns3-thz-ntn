def stage_verify():
    r = R()
    f = r["f"]
    cpp, mirror, ref = r["cpp"], r["mirror"], r["ref"]
    rel = np.abs(cpp - mirror) / np.maximum(mirror, 1e-12)
    mac("MirrorMaxRelErr", texsci(rel.max()))
    mac("MirrorPoints", int(cpp.size), "{:d}")
    h0_, d0_ = A.annex1_layers()
    mac("ColumnDefault", A.column_mm(h0_, d0_, A.p835_rho(h0_ + 0.5 * d0_)), "{:.2f}")
    cs = centers(r)
    for (name, *_), c in zip(WINDOWS, cs):
        mac(f"Ctr{WN[name]}", c, "{:.2f}")
    json.dump({"centers": cs}, open(os.path.join(OUT, "windows.json"), "w"))
    # ITU-Rpy Annex 1 (independent): default profile, rho0 = 7.5
    ip = int(np.argmin(np.abs(r["pwv"] - 15.0)))
    res = {}
    h, d = A.annex1_layers()
    hm = h + 0.5 * d
    T, P, rho = A.state(hm, rho0=7.5)
    n = A.refractive_index(T, P, rho)
    G = A.gamma_grid(np.array(cs), hm, T, P, rho)
    # ITU-Rpy feeds TOTAL pressure where the recommendation asks for the dry
    # partial pressure and uses no mixing-ratio floor; replicate both to
    # show the residual is those two choices.
    # ... and samples each layer at its lower boundary, not its midpoint.
    Tb, Pb = A.p835_TP(h)
    rho_nf = 7.5 * np.exp(-h / 2.0)
    Gtp = np.stack([A.gamma_p676(np.array(cs), Tb[i], Pb[i] + rho_nf[i] * Tb[i] / 216.7, rho_nf[i])
                    for i in range(len(h))])
    n_tp = 1 + 1e-6 * (77.6 * Pb / Tb + 72 * (rho_nf * Tb / 216.7) / Tb
                       + 3.75e5 * (rho_nf * Tb / 216.7) / Tb ** 2)
    rows = []
    for e in (10, 30, 90):
        ours = A.annex1_path_lengths(e, h, d, n) @ G
        itr = A.itur_annex1(cs, e, 7.5)
        ours_tp = A.annex1_path_lengths(e, h, d, n_tp) @ Gtp
        rows.append((e, ours, itr, ours_tp))
    d1 = np.array([np.abs(o - i) / i for e, o, i, t in rows])
    d2 = np.array([np.abs(t - i) / i for e, o, i, t in rows])
    mac("AppElevOffsetTen", A.apparent_elevation(10.0, h, d, n) - 10.0, "{:.3f}")
    mac("ItuRpyMaxRelPct", 100 * d1.max(), "{:.1f}")
    mac("ItuRpyMaxRelPctMatched", 100 * d2.max(), "{:.3f}")
    mac("ItuRpyMaxRelMatchedSci", texsci(d2.max()))
    mac("ItuRpyMaxAbsDb", max(np.abs(o - i).max() for e, o, i, t in rows), "{:.1f}")
    e0, o0, i0, t0 = max(rows, key=lambda r: np.abs(r[1] - r[2]).max())
    k0 = int(np.argmax(np.abs(o0 - i0)))
    mac("ItuRpyMaxAbsAtLoss", o0[k0], "{:.0f}")
    mac("ItuRpyMaxAbsAtElev", e0, "{:d}")
    mac("ItuRpyMaxAbsAtFreq", cs[k0], "{:.0f}")
    json.dump({"rows": [(e, list(o), list(i), list(t)) for e, o, i, t in rows]},
              open(os.path.join(OUT, "verify_itur.json"), "w"))
    # LUT paths (as-published atmosphere, PWV 15 mm)
    import csv
    def pub(name):
        d = {}
        for row in csv.DictReader(open(os.path.join(OUT, name))):
            d[(float(row["elev_deg"]), float(row["freq_ghz"]))] = float(row["atten_db"])
        return d
    inp, lut, leg = pub("cpp_inproc_pub.csv"), pub("cpp_lut.csv"), pub("cpp_lut_legacy.csv")
    k_all = [k for k in inp]
    dl = np.array([lut[k] - inp[k] for k in k_all])
    mac("LutNewMaxAbsDb", np.abs(dl).max(), "{:.2f}")
    win = [k for k in k_all if any(abs(k[1] - c) <= 5 for c in cs)]
    mac("LutNewWinMaxAbsDb", max(abs(lut[k] - inp[k]) for k in win if inp[k] <= AMAX), "{:.3f}")
    mac("LutNewWinMaxPct", 100 * max(abs(lut[k] - inp[k]) / inp[k] for k in win), "{:.2f}")
    mac("LutNewMaxPct", 100 * float(np.max(np.abs(dl) / np.array([inp[k] for k in k_all]))), "{:.1f}")
    kl = [k for k in leg if k in inp]
    dleg = np.array([leg[k] - inp[k] for k in kl])
    rl = np.array([(leg[k] - inp[k]) / inp[k] for k in kl])
    mac("LutOldMaxAbsDb", np.abs(dleg).max(), "{:.1f}")
    mac("LutOldMaxRelPct", 100 * np.abs(rl).max(), "{:.0f}")
    c340 = [(e, leg[(e, cs[0])] - inp[(e, cs[0])], inp[(e, cs[0])]) for e in (10.0, 30.0, 90.0)]
    mac("LutOldCtrThreeFortyTenDb", c340[0][1], "{:+.1f}")
    mac("LutOldCtrThreeFortyTenRef", c340[0][2], "{:.1f}")
    st = pub("cpp_inproc_steps200.csv")
    ds = [abs(inp[k] - st[k]) / st[k] for k in st if k in inp]
    mac("QuadMaxRelPct", 100 * max(ds), "{:.2f}")
    # THZ-15: effect of the floor definition (mass vs volume mixing ratio)
    T, P = A.p835_TP(hm)
    rho_e = 7.5 * np.exp(-hm / 2.0)
    e = rho_e * T / 216.7
    mr = 0.622 * e / (P - e)
    rho_old = np.where(mr < 2e-6, 2e-6 * P / (0.622 + 2e-6) * 216.7 / T, rho_e)
    rho_new = A.p835_rho(hm)
    n = A.refractive_index(T, P, rho_new)
    a30 = A.annex1_path_lengths(10, h, d, n)
    dfl = np.abs(a30 @ A.gamma_grid(np.array(cs), hm, T, P, rho_old)
                 - a30 @ A.gamma_grid(np.array(cs), hm, T, P, rho_new)).max()
    mac("FloorEffectDb", dfl, "{:.4f}")
    for pv, tag in ((15.0, "GlobalFifteen"), (20.0, "GlobalTwenty")):
        Tg, Pg, rg = A.state(hm, pwv_mm=pv)
        mac(f"RhMax{tag}", 100 * A.max_rh(hm, Tg, rg), "{:.0f}")
    sc, _ = A.scale_for_pwv(50.0)
    Tl, Pl, rl = A.atm_state(hm, "low", sc)
    mac("RhMaxLowFifty", 100 * A.max_rh(hm, Tl, rl), "{:.0f}")
    print("verify done")


