#!/usr/bin/env python3
"""Fail if the submitted manuscript (main_v7.tex, supplement_v7.tex, sections_v7/; also the v6 files) uses a generated
macro that no macro file of this run defines, or if a macro file is missing or older than the run."""
import glob, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
P = os.path.join(HERE, "..")
FILES = ("macros.tex", "am_macros.tex", "am_slant_macros.tex", "meas_macros.tex", "meas2_macros.tex",
         "heff_macros.tex", "oosci_macros.tex", "budget_macros.tex", "sonde_rate_macros.tex", "p835v7_macros.tex", "arctic_macros.tex")
start = float(os.environ.get("RUN_START", "0"))
defined = set()
for f in FILES:
    pth = os.path.join(P, f)
    if not os.path.exists(pth) or os.path.getmtime(pth) < start:
        print("STALE OR MISSING:", f)
        sys.exit(1)
    for line in open(pth):
        m = re.match(r"\\newcommand\{\\([A-Za-z]+)\}", line)
        if m:
            defined.add(m.group(1))
tex = [os.path.join(P, n) for n in ("main_v7.tex", "supplement_v7.tex", "main_v6.tex", "supplement_v6.tex")] + glob.glob(os.path.join(P, "sections_v7", "*.tex")) + glob.glob(os.path.join(P, "sections_v6", "*.tex"))
used = set()
for f in tex:
    src = re.sub(r"(?<!\\)%.*", "", open(f).read())
    used |= set(re.findall(r"\\([A-Z][a-z]+(?:[A-Z][a-z]*)+)", src))
known = {"IEEEPARstart", "IEEEkeywords", "IEEEbiography", "IEEEmembership", "MakeUppercase"}
missing = sorted(u for u in used - defined - known)
print(f"{len(used)} CamelCase macros used, {len(defined)} defined, in {len(tex)} files")
if missing:
    print("UNDEFINED:", " ".join(missing))
    sys.exit(1)
print("all manuscript macros are generated by this run")
